def safe_method_order(methods: List[str]) -> List[str]:
    order = CORE_METHODS + OPTIONAL_METHODS + ["ValidationRMSE_Selected_Model", "StrategyBestFixedByValidation"]
    seen = []
    for m in order + sorted(methods):
        if m in methods and m not in seen:
            seen.append(m)
    return seen


