def write_decision_report(summary_all: pd.DataFrame,
                          robust_rank: pd.DataFrame,
                          selected_split: pd.DataFrame,
                          strategy_best: pd.DataFrame,
                          high_error_diag: pd.DataFrame,
                          residual_corr: pd.DataFrame,
                          residual_learning_summary: pd.DataFrame):
    path = TABLE_DIR / "31p_rmse_global_decision.txt"
    lines = []
    lines.append("=" * 100)
    lines.append("Step 31P all-domain RMSE-oriented global optimization and decision report")
    lines.append("=" * 100)
    lines.append("")
    lines.append("Purpose:")
    lines.append("Perform the final all-domain RMSE-oriented decision step before applicability-domain analysis.")
    lines.append("")
    lines.append("Strict workflow:")
    lines.append("- No samples or literature groups are removed.")
    lines.append("- ValidationRMSE_Selected_Model is selected per split/fold only by validation RMSE.")
    lines.append("- StrategyBestFixedByValidation is selected per validation strategy only by mean validation RMSE.")
    lines.append("- Test labels are never used for deployable model/policy selection.")
    lines.append("- OracleBestPaper_DiagnosticOnly uses held-out labels and is diagnostic only, not a deployable model.")
    lines.append("")

    lines.append("RMSE-oriented summary by strategy and method:")
    display_cols = ["Source", "Strategy", "Method", "Pooled_R2", "Pooled_RMSE", "Pooled_MAE", "Pooled_Bias", "n_pooled", "n_splits", "n_papers"]
    lines.append(summary_all[display_cols].sort_values(["Strategy", "Pooled_RMSE"]).to_string(index=False))
    lines.append("")

    lines.append("Robust RMSE ranking across validation strategies:")
    lines.append(robust_rank.to_string(index=False))
    lines.append("")

    lines.append("Validation-RMSE selected model counts:")
    if not selected_split.empty:
        counts = selected_split.groupby(["Strategy", "Method"], as_index=False).size().rename(columns={"size": "Selection_Count"})
        lines.append(counts.to_string(index=False))
    lines.append("")

    lines.append("Strategy-level fixed model selected by validation RMSE:")
    if not strategy_best.empty:
        lines.append(strategy_best.to_string(index=False))
    lines.append("")

    if not residual_corr.empty:
        lines.append("Residual-correlation reminder from 31N:")
        tmp = residual_corr.sort_values(["Strategy", "Residual_Correlation_with_KRR"]).groupby("Strategy").head(3)
        lines.append(tmp.to_string(index=False))
        lines.append("")

    if not residual_learning_summary.empty:
        lines.append("31O residual-learning reminder:")
        cols = [c for c in ["Method", "Pooled_R2", "Pooled_RMSE", "Pooled_MAE", "Pooled_Bias"] if c in residual_learning_summary.columns]
        lines.append(residual_learning_summary.sort_values("Pooled_RMSE")[cols].head(8).to_string(index=False))
        lines.append("")

    lines.append("High-error LOLO papers diagnostic:")
    if not high_error_diag.empty:
        cols = [
            "文献编号", "n_samples", "Observed_mean", "Observed_std",
            "KRR_Poly_Paper_RMSE", "XGBoost_Paper_RMSE", "CBXGB_Paper_RMSE",
            "Oracle_Best_Method_DiagnosticOnly", "Oracle_Best_Paper_RMSE_DiagnosticOnly",
            "KRR_minus_oracle_RMSE",
        ]
        cols = [c for c in cols if c in high_error_diag.columns]
        lines.append(high_error_diag[cols].head(20).to_string(index=False))
    lines.append("")

    # Final recommendation
    best_robust = robust_rank.iloc[0] if len(robust_rank) else None
    lines.append("Decision:")
    if best_robust is not None:
        lines.append(f"- Most robust all-domain RMSE candidate/policy by rank: {best_robust['Method']}.")
    lines.append("- If ValidationRMSE_Selected_Model does not clearly beat the best fixed model, do not add policy complexity.")
    lines.append("- If the best model differs across LOLO/GroupKFold/balanced splits, report validation-form sensitivity instead of claiming a single universally best global model.")
    lines.append("- If all fully grouped RMSE values remain high and all R2 values stay far below 0.5, stop global model forcing and proceed to applicability-domain analysis.")
    lines.append("- Paper-level macro RMSE must be reported beside pooled RMSE because pooled metrics can be dominated by large literature groups.")
    lines.append("")
    lines.append("Recommended next step:")
    lines.append("32A applicability-domain analysis: quantify coverage, extrapolation risk, high-error paper characteristics, and reliable-domain performance without deleting data from the all-domain report.")
    lines.append("=" * 100)

    path.write_text("\n".join(lines), encoding="utf-8")
    log(f"Saved decision report: {path}")


