        vals = data[col].values
        bars = ax.bar(x + (i - 1.5) * width, vals, width=width, label=method, color=COLORS.get(method, COLORS["gray"]), edgecolor="black", linewidth=0.35, alpha=0.85)
        for b, v in zip(bars, vals):
            if np.isfinite(v):
                ax.text(b.get_x()+b.get_width()/2, b.get_height(), f"{v:.1f}", ha="center", va="bottom", fontsize=6, rotation=90)
