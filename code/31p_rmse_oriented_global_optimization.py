def select_model_per_split_by_validation_rmse(test_df: pd.DataFrame) -> pd.DataFrame:
    """Choose one model per Strategy/Split_ID by Validation_RMSE only."""
    required = {"Strategy", "Split_ID", "Method", "Validation_RMSE"}
    missing = required - set(test_df.columns)
    if missing:
        raise ValueError(f"31N test results missing required columns: {missing}")

    rows = []
    for (strategy, split_id), sub in test_df.groupby(["Strategy", "Split_ID"]):
        candidates = sub[sub["Method"].isin(POLICY_METHOD_POOL)].copy()
        candidates = candidates[np.isfinite(candidates["Validation_RMSE"].astype(float))]
        if candidates.empty:
            continue
        candidates = candidates.sort_values(["Validation_RMSE", "Validation_MAE", "Method"], ascending=[True, True, True])
        best = candidates.iloc[0].copy()
        row = best.to_dict()
        row["Selected_By"] = "Lowest validation RMSE within policy pool"
        row["Policy_Method"] = "ValidationRMSE_Selected_Model"
        rows.append(row)

    selected = pd.DataFrame(rows)
    return selected.reset_index(drop=True)


def make_policy_predictions(pred_df: pd.DataFrame, selected_df: pd.DataFrame) -> pd.DataFrame:
    required = {"Strategy", "Split_ID", "Method", "Observed", "Predicted", "文献编号", "Data_Index"}
    missing = required - set(pred_df.columns)
    if missing:
        raise ValueError(f"31N predictions missing required columns: {missing}")

    keep_keys = selected_df[["Strategy", "Split_ID", "Method"]].copy()
    keep_keys["Policy_Method"] = "ValidationRMSE_Selected_Model"

    merged = pred_df.merge(keep_keys, on=["Strategy", "Split_ID", "Method"], how="inner")
    merged = merged.copy()
    merged["Original_Selected_Method"] = merged["Method"]
    merged["Method"] = merged["Policy_Method"]
    merged["Residual"] = merged["Observed"] - merged["Predicted"]
    return merged.drop(columns=["Policy_Method"]).reset_index(drop=True)


def select_strategy_best_fixed_by_validation(test_df: pd.DataFrame) -> pd.DataFrame:
    """Choose one fixed model per validation strategy using mean Validation_RMSE only."""
    candidates = test_df[test_df["Method"].isin(POLICY_METHOD_POOL)].copy()
    candidates = candidates[np.isfinite(candidates["Validation_RMSE"].astype(float))]
    rows = []
    for strategy, sub in candidates.groupby("Strategy"):
        g = (
            sub.groupby("Method", as_index=False)
            .agg(
                Mean_Validation_RMSE=("Validation_RMSE", "mean"),
                Median_Validation_RMSE=("Validation_RMSE", "median"),
                Mean_Validation_MAE=("Validation_MAE", "mean"),
                n_splits=("Split_ID", "nunique"),
            )
            .sort_values(["Mean_Validation_RMSE", "Mean_Validation_MAE", "Method"], ascending=[True, True, True])
        )
        if len(g):
            row = g.iloc[0].to_dict()
            row["Strategy"] = strategy
            row["Policy_Method"] = "StrategyBestFixedByValidation"
            rows.append(row)
    return pd.DataFrame(rows)


def make_strategy_best_predictions(pred_df: pd.DataFrame, strategy_best_df: pd.DataFrame) -> pd.DataFrame:
    if strategy_best_df.empty:
        return pd.DataFrame()
    keys = strategy_best_df[["Strategy", "Method"]].copy()
    keys["Policy_Method"] = "StrategyBestFixedByValidation"
    merged = pred_df.merge(keys, on=["Strategy", "Method"], how="inner")
    merged = merged.copy()
    merged["Original_Selected_Method"] = merged["Method"]
    merged["Method"] = merged["Policy_Method"]
    merged["Residual"] = merged["Observed"] - merged["Predicted"]
    return merged.drop(columns=["Policy_Method"]).reset_index(drop=True)


