"""
31p_rmse_oriented_global_optimization.py

Purpose
-------
Final all-domain RMSE-oriented optimization/decision step before moving to
applicability-domain analysis.

This script does NOT remove any literature group, paper, or sample. It works on
all-domain fully grouped validation outputs generated by Step 31N and residual
learning outputs from Step 31O.

Core question
-------------
After Steps 31F-31O, can we still reduce all-domain grouped RMSE by selecting
models more carefully across fully grouped validation forms, without using test
labels for model selection?

What this script does
---------------------
1. Read Step-31N outputs:
   - 31n_grouped_validation_summary.csv
   - 31n_grouped_validation_test_results.csv
   - 31n_grouped_validation_predictions.csv
   - 31n_grouped_validation_paper_metrics.csv
   - 31n_grouped_validation_paper_macro_summary.csv
   - 31n_low_residual_correlation_screen.csv

2. Read Step-31O outputs if available:
   - 31o_residual_learning_summary.csv
   - 31o_oof_residual_correlation_screen.csv

3. Build a strict validation-RMSE model-selection policy:
   For each fully grouped split/fold, choose the model with the lowest
   Validation_RMSE among the allowed candidate pool, then evaluate that chosen
   model on the corresponding held-out test groups.

   Important: test labels are NOT used to select the chosen model. Test labels
   are used only after selection to evaluate the policy.

4. Compare three families of all-domain candidates:
   - Fixed models from 31N: KRR_Poly, CatBoost, XGBoost, CB-XGB,
     KRR_CatBoost_Weighted_2Model, KRR_XGBoost_Weighted_2Model.
   - ValidationRMSE_Selected_Model: model selected per split using validation
     RMSE only.
   - StrategyBestFixedByValidation: one fixed model selected per validation
     strategy using mean validation RMSE only.

5. Create RMSE-oriented decision summaries:
   - Pooled RMSE ranking.
   - Paper-level macro RMSE ranking.
   - Robust RMSE rank across validation strategies.
   - LOLO high-error paper diagnosis.
   - Diagnostic oracle-per-paper lower bound. This uses test labels only as a
     diagnostic bound and is explicitly NOT a deployable model.

Strictness rules
----------------
- 文献编号 is never used as a model input here; this script only reads already
  generated grouped-validation predictions and diagnostics.
- Test labels are never used to select ValidationRMSE_Selected_Model or
  StrategyBestFixedByValidation.
- Oracle-per-paper results are marked diagnostic only and must not be reported
  as an achieved model performance.
- No applicability-domain filtering is applied in this script.
- Total runtime is printed at the end.

Outputs
-------
Tables:
    outputs/tables/31p_rmse_policy_selected_by_split.csv
    outputs/tables/31p_rmse_policy_predictions.csv
    outputs/tables/31p_rmse_policy_summary.csv
    outputs/tables/31p_rmse_strategy_robust_ranking.csv
    outputs/tables/31p_rmse_high_error_paper_diagnosis.csv
    outputs/tables/31p_rmse_oracle_paper_switching_diagnostic.csv
    outputs/tables/31p_rmse_global_decision.txt

Figures:
    outputs/figures/135_31p_rmse_policy_metrics.png/pdf
    outputs/figures/136_31p_strategy_rmse_rank_heatmap.png/pdf
    outputs/figures/137_31p_lolo_high_error_papers.png/pdf
    outputs/figures/138_31p_policy_pooled_predicted_vs_actual.png/pdf
"""

