def plot_policy_metrics(summary_all: pd.DataFrame):
    methods = [
        "ValidationRMSE_Selected_Model",
        "StrategyBestFixedByValidation",
        "KRR_Poly",
        "KRR_CatBoost_Weighted_2Model",
        "CB-XGB",
        "CatBoost",
        "XGBoost",
    ]
    data = summary_all[summary_all["Method"].isin(methods)].copy()
    strategies = [s for s in STRATEGY_ORDER if s in data["Strategy"].unique()]
    methods = [m for m in methods if m in data["Method"].unique()]

    fig, axes = plt.subplots(1, 3, figsize=(18, 5.2))
    specs = [("Pooled_R2", "Pooled $R^2$", "{:.3f}"), ("Pooled_RMSE", "Pooled RMSE", "{:.2f}"), ("Pooled_MAE", "Pooled MAE", "{:.2f}")]
    width = 0.11 if len(methods) > 6 else 0.13
    x = np.arange(len(strategies))
    for ax, (col, title, fmt) in zip(axes, specs):
        for i, method in enumerate(methods):
            vals = []
            for strategy in strategies:
                sub = data[(data["Strategy"] == strategy) & (data["Method"] == method)]
                vals.append(float(sub[col].iloc[0]) if len(sub) else np.nan)
            offset = (i - (len(methods) - 1) / 2) * width
            bars = ax.bar(x + offset, vals, width=width, label=method, color=COLORS.get(method, COLORS["gray"]), edgecolor="black", linewidth=0.35, alpha=0.85)
            for b, v in zip(bars, vals):
                if np.isfinite(v):
                    ax.text(b.get_x() + b.get_width()/2, b.get_height(), fmt.format(v), ha="center", va="bottom", fontsize=5.8, rotation=90)
        ax.set_xticks(x)
        ax.set_xticklabels(strategies, rotation=28, ha="right")
        ax.set_title(title)
        ax.set_ylabel(title)
        ax.grid(axis="y", color=COLORS["grid"], linewidth=0.7, alpha=0.8)
        if col == "Pooled_R2":
            ax.axhline(0, color="black", linewidth=0.8)
    axes[0].legend(frameon=False, fontsize=6.5, loc="best")
    fig.suptitle("31P all-domain RMSE-oriented model-selection policy", fontsize=15, fontweight="bold")
    fig.text(0.5, 0.01, "Policy models are selected only by validation RMSE; no applicability-domain filtering is applied.", ha="center", fontsize=8)
    save_fig(fig, "135_31p_rmse_policy_metrics.png")


def plot_rank_heatmap(summary_all: pd.DataFrame):
    methods = [
        "ValidationRMSE_Selected_Model",
        "StrategyBestFixedByValidation",
        "KRR_Poly",
        "KRR_CatBoost_Weighted_2Model",
        "CB-XGB",
        "CatBoost",
        "XGBoost",
    ]
    data = summary_all[summary_all["Method"].isin(methods)].copy()
    strategies = [s for s in STRATEGY_ORDER if s in data["Strategy"].unique()]
    methods = [m for m in methods if m in data["Method"].unique()]

    mat = np.full((len(methods), len(strategies)), np.nan)
    for j, strategy in enumerate(strategies):
        sub = data[data["Strategy"] == strategy].copy()
        sub["RMSE_Rank"] = sub["Pooled_RMSE"].rank(method="average", ascending=True)
        for i, method in enumerate(methods):
            ss = sub[sub["Method"] == method]
            if len(ss):
                mat[i, j] = float(ss["RMSE_Rank"].iloc[0])

    fig, ax = plt.subplots(figsize=(11, 5.5))
    im = ax.imshow(mat, aspect="auto", cmap="YlGnBu_r", vmin=1, vmax=np.nanmax(mat))
    ax.set_xticks(np.arange(len(strategies)))
    ax.set_xticklabels(strategies, rotation=28, ha="right")
    ax.set_yticks(np.arange(len(methods)))
    ax.set_yticklabels(methods)
    for i in range(len(methods)):
        for j in range(len(strategies)):
            if np.isfinite(mat[i, j]):
                ax.text(j, i, f"{mat[i, j]:.1f}", ha="center", va="center", fontsize=8)
    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label("Pooled RMSE rank within validation strategy (lower is better)")
    ax.set_title("RMSE rank stability across fully grouped validation strategies", fontweight="bold")
    save_fig(fig, "136_31p_strategy_rmse_rank_heatmap.png")


