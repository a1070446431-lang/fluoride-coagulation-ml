def summarize_predictions(pred_df: pd.DataFrame, source: str) -> pd.DataFrame:
    rows = []
    for (strategy, method), sub in pred_df.groupby(["Strategy", "Method"]):
        m = regression_metrics(sub["Observed"], sub["Predicted"])
        rows.append({
            "Source": source,
            "Strategy": strategy,
            "Method": method,
            "Pooled_R2": m["R2"],
            "Pooled_RMSE": m["RMSE"],
            "Pooled_MAE": m["MAE"],
            "Pooled_MSE": m["MSE"],
            "Pooled_Bias": m["Bias"],
            "n_pooled": m["n"],
            "n_splits": sub["Split_ID"].nunique(),
            "n_papers": sub["文献编号"].nunique(),
        })
    return pd.DataFrame(rows)


def summarize_paper_macro(pred_df: pd.DataFrame, source: str) -> Tuple[pd.DataFrame, pd.DataFrame]:
    paper_rows = []
    for (strategy, method, paper), sub in pred_df.groupby(["Strategy", "Method", "文献编号"]):
        m = regression_metrics(sub["Observed"], sub["Predicted"])
        paper_rows.append({
            "Source": source,
            "Strategy": strategy,
            "Method": method,
            "文献编号": paper,
            "Paper_R2": m["R2"],
            "Paper_RMSE": m["RMSE"],
            "Paper_MAE": m["MAE"],
            "Paper_Bias": m["Bias"],
            "n_samples": m["n"],
            "Observed_mean": float(np.mean(sub["Observed"])),
            "Predicted_mean": float(np.mean(sub["Predicted"])),
        })
    paper_df = pd.DataFrame(paper_rows)
    if paper_df.empty:
        return paper_df, pd.DataFrame()
    macro = (
        paper_df.groupby(["Source", "Strategy", "Method"], as_index=False)
        .agg(
            PaperMacro_RMSE_mean=("Paper_RMSE", "mean"),
            PaperMacro_RMSE_median=("Paper_RMSE", "median"),
            PaperMacro_MAE_mean=("Paper_MAE", "mean"),
            PaperMacro_MAE_median=("Paper_MAE", "median"),
            PaperMacro_Bias_mean=("Paper_Bias", "mean"),
            n_papers=("文献编号", "nunique"),
        )
    )
    return paper_df, macro


def build_strategy_robust_ranking(summary: pd.DataFrame, macro: pd.DataFrame) -> pd.DataFrame:
    """RMSE-oriented robust ranking across strategies.

    Score is rank-based to avoid mixing strategies with different sample counts.
    Lower score is better.
    """
    pooled = summary.copy()
    pooled = pooled[pooled["Method"].isin(POLICY_METHOD_POOL + ["ValidationRMSE_Selected_Model", "StrategyBestFixedByValidation"])]
    pooled["Pooled_RMSE_Rank_in_Strategy"] = pooled.groupby("Strategy")["Pooled_RMSE"].rank(method="average", ascending=True)
    pooled["Pooled_MAE_Rank_in_Strategy"] = pooled.groupby("Strategy")["Pooled_MAE"].rank(method="average", ascending=True)

    macro_small = macro[["Strategy", "Method", "PaperMacro_RMSE_mean", "PaperMacro_MAE_mean"]].copy() if not macro.empty else pd.DataFrame()
    if not macro_small.empty:
        macro_small["PaperMacro_RMSE_Rank_in_Strategy"] = macro_small.groupby("Strategy")["PaperMacro_RMSE_mean"].rank(method="average", ascending=True)
        macro_small["PaperMacro_MAE_Rank_in_Strategy"] = macro_small.groupby("Strategy")["PaperMacro_MAE_mean"].rank(method="average", ascending=True)
        pooled = pooled.merge(macro_small, on=["Strategy", "Method"], how="left")
    else:
        pooled["PaperMacro_RMSE_Rank_in_Strategy"] = np.nan
        pooled["PaperMacro_MAE_Rank_in_Strategy"] = np.nan

    # Pooled RMSE and paper-macro RMSE are given the highest weight.
    pooled["RMSE_Weighted_Rank"] = (
        0.50 * pooled["Pooled_RMSE_Rank_in_Strategy"] +
        0.25 * pooled["PaperMacro_RMSE_Rank_in_Strategy"].fillna(pooled["Pooled_RMSE_Rank_in_Strategy"]) +
        0.15 * pooled["Pooled_MAE_Rank_in_Strategy"] +
        0.10 * pooled["PaperMacro_MAE_Rank_in_Strategy"].fillna(pooled["Pooled_MAE_Rank_in_Strategy"])
    )

    rank = (
        pooled.groupby("Method", as_index=False)
        .agg(
            Robust_RMSE_Rank_Mean=("RMSE_Weighted_Rank", "mean"),
            Robust_RMSE_Rank_Median=("RMSE_Weighted_Rank", "median"),
            Best_Strategy_Count=("RMSE_Weighted_Rank", lambda x: int(np.sum(np.asarray(x) == np.nanmin(x)))),
            Mean_Pooled_RMSE=("Pooled_RMSE", "mean"),
            Median_Pooled_RMSE=("Pooled_RMSE", "median"),
            Mean_Pooled_MAE=("Pooled_MAE", "mean"),
            Strategies_Covered=("Strategy", "nunique"),
        )
        .sort_values(["Robust_RMSE_Rank_Mean", "Mean_Pooled_RMSE"], ascending=[True, True])
        .reset_index(drop=True)
    )
    rank["Robust_RMSE_Rank_Position"] = np.arange(1, len(rank) + 1)
    return rank


def build_high_error_diagnosis(pred_df: pd.DataFrame, strategy: str = "LOLO_LeaveOneLiteratureOut") -> Tuple[pd.DataFrame, pd.DataFrame]:
    data = pred_df[(pred_df["Strategy"] == strategy) & (pred_df["Method"].isin(CORE_METHODS))].copy()
    if data.empty:
        return pd.DataFrame(), pd.DataFrame()

    paper_rows = []
    for (paper, method), sub in data.groupby(["文献编号", "Method"]):
        m = regression_metrics(sub["Observed"], sub["Predicted"])
        paper_rows.append({
            "Strategy": strategy,
            "文献编号": paper,
            "Method": method,
            "Paper_RMSE": m["RMSE"],
            "Paper_MAE": m["MAE"],
            "Paper_Bias": m["Bias"],
            "Paper_R2": m["R2"],
            "n_samples": m["n"],
            "Observed_mean": float(np.mean(sub["Observed"])),
            "Observed_std": float(np.std(sub["Observed"])),
        })
    paper_df = pd.DataFrame(paper_rows)

    # Best model per paper diagnostic. This uses held-out labels and is diagnostic only.
    best = paper_df.sort_values(["文献编号", "Paper_RMSE"]).groupby("文献编号", as_index=False).first()
    best = best.rename(columns={
        "Method": "Oracle_Best_Method_DiagnosticOnly",
        "Paper_RMSE": "Oracle_Best_Paper_RMSE_DiagnosticOnly",
        "Paper_MAE": "Oracle_Best_Paper_MAE_DiagnosticOnly",
    })

    krr = paper_df[paper_df["Method"] == "KRR_Poly"][["文献编号", "Paper_RMSE", "Paper_MAE"]].rename(columns={
        "Paper_RMSE": "KRR_Poly_Paper_RMSE",
        "Paper_MAE": "KRR_Poly_Paper_MAE",
    })
    xgb = paper_df[paper_df["Method"] == "XGBoost"][["文献编号", "Paper_RMSE", "Paper_MAE"]].rename(columns={
        "Paper_RMSE": "XGBoost_Paper_RMSE",
        "Paper_MAE": "XGBoost_Paper_MAE",
    })
    cbxgb = paper_df[paper_df["Method"] == "CB-XGB"][["文献编号", "Paper_RMSE", "Paper_MAE"]].rename(columns={
        "Paper_RMSE": "CBXGB_Paper_RMSE",
        "Paper_MAE": "CBXGB_Paper_MAE",
    })

    diag = best.merge(krr, on="文献编号", how="left").merge(xgb, on="文献编号", how="left").merge(cbxgb, on="文献编号", how="left")
    diag["KRR_minus_oracle_RMSE"] = diag["KRR_Poly_Paper_RMSE"] - diag["Oracle_Best_Paper_RMSE_DiagnosticOnly"]
    diag["XGB_minus_oracle_RMSE"] = diag["XGBoost_Paper_RMSE"] - diag["Oracle_Best_Paper_RMSE_DiagnosticOnly"]
    diag["CBXGB_minus_oracle_RMSE"] = diag["CBXGB_Paper_RMSE"] - diag["Oracle_Best_Paper_RMSE_DiagnosticOnly"]
    diag = diag.sort_values("KRR_Poly_Paper_RMSE", ascending=False).reset_index(drop=True)
    return paper_df, diag


