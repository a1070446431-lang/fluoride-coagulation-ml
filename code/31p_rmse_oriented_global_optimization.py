def main():
    log("=" * 100)
    log("31P all-domain RMSE-oriented global optimization")
    log(f"Project root: {PROJECT_ROOT}")
    log("=" * 100)

    n_summary = read_required_csv("31n_grouped_validation_summary.csv")
    n_test = read_required_csv("31n_grouped_validation_test_results.csv")
    n_pred = read_required_csv("31n_grouped_validation_predictions.csv")
    n_paper = read_required_csv("31n_grouped_validation_paper_metrics.csv")
    n_macro = read_required_csv("31n_grouped_validation_paper_macro_summary.csv")
    n_low_corr = read_required_csv("31n_low_residual_correlation_screen.csv")

    o_summary = read_optional_csv("31o_residual_learning_summary.csv")
    o_corr = read_optional_csv("31o_oof_residual_correlation_screen.csv")

    # Keep original fixed models from 31N predictions.
    fixed_pred = n_pred[n_pred["Method"].isin(POLICY_METHOD_POOL)].copy()
    fixed_summary = summarize_predictions(fixed_pred, source="31N_fixed_models")
    _, fixed_macro = summarize_paper_macro(fixed_pred, source="31N_fixed_models")

    # Policy 1: select model per split by validation RMSE.
    selected_split = select_model_per_split_by_validation_rmse(n_test)
    policy_pred = make_policy_predictions(n_pred, selected_split)
    policy_summary = summarize_predictions(policy_pred, source="31P_validation_rmse_policy")
    _, policy_macro = summarize_paper_macro(policy_pred, source="31P_validation_rmse_policy")

    # Policy 2: fixed method per strategy selected by validation RMSE.
    strategy_best = select_strategy_best_fixed_by_validation(n_test)
    strategy_best_pred = make_strategy_best_predictions(n_pred, strategy_best)
    strategy_best_summary = summarize_predictions(strategy_best_pred, source="31P_strategy_fixed_validation_choice") if not strategy_best_pred.empty else pd.DataFrame()
    _, strategy_best_macro = summarize_paper_macro(strategy_best_pred, source="31P_strategy_fixed_validation_choice") if not strategy_best_pred.empty else (pd.DataFrame(), pd.DataFrame())

    summary_all = pd.concat([fixed_summary, policy_summary, strategy_best_summary], ignore_index=True)
    macro_all = pd.concat([fixed_macro, policy_macro, strategy_best_macro], ignore_index=True)

    # Robust ranking across all validation strategies.
    robust_rank = build_strategy_robust_ranking(summary_all, macro_all)

    # High-error paper diagnosis, LOLO only.
    lolo_paper, high_error_diag = build_high_error_diagnosis(fixed_pred, strategy="LOLO_LeaveOneLiteratureOut")

    # Save tables.
    selected_split.to_csv(TABLE_DIR / "31p_rmse_policy_selected_by_split.csv", index=False, encoding="utf-8-sig")
    policy_pred.to_csv(TABLE_DIR / "31p_rmse_policy_predictions.csv", index=False, encoding="utf-8-sig")
    summary_all.to_csv(TABLE_DIR / "31p_rmse_policy_summary.csv", index=False, encoding="utf-8-sig")
    robust_rank.to_csv(TABLE_DIR / "31p_rmse_strategy_robust_ranking.csv", index=False, encoding="utf-8-sig")
    high_error_diag.to_csv(TABLE_DIR / "31p_rmse_high_error_paper_diagnosis.csv", index=False, encoding="utf-8-sig")
    lolo_paper.to_csv(TABLE_DIR / "31p_rmse_lolo_paper_model_metrics.csv", index=False, encoding="utf-8-sig")
    high_error_diag.to_csv(TABLE_DIR / "31p_rmse_oracle_paper_switching_diagnostic.csv", index=False, encoding="utf-8-sig")

    # Figures.
    plot_policy_metrics(summary_all)
    plot_rank_heatmap(summary_all)
    plot_lolo_high_error(high_error_diag)
    plot_policy_predicted_vs_actual(policy_pred, fixed_pred)

    # Decision report.
    write_decision_report(
        summary_all=summary_all,
        robust_rank=robust_rank,
        selected_split=selected_split,
        strategy_best=strategy_best,
        high_error_diag=high_error_diag,
        residual_corr=n_low_corr,
        residual_learning_summary=o_summary,
    )

    log("\nSaved tables:")
    for name in [
        "31p_rmse_policy_selected_by_split.csv",
        "31p_rmse_policy_predictions.csv",
        "31p_rmse_policy_summary.csv",
        "31p_rmse_strategy_robust_ranking.csv",
        "31p_rmse_high_error_paper_diagnosis.csv",
        "31p_rmse_oracle_paper_switching_diagnostic.csv",
        "31p_rmse_global_decision.txt",
    ]:
        log(str(TABLE_DIR / name))

    log("\nSaved figures:")
    for name in [
        "135_31p_rmse_policy_metrics.png",
        "136_31p_strategy_rmse_rank_heatmap.png",
        "137_31p_lolo_high_error_papers.png",
        "138_31p_policy_pooled_predicted_vs_actual.png",
    ]:
        log(str(FIG_DIR / name))


if __name__ == "__main__":
    start_time = time.time()
    main()
