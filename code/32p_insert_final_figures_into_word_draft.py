def set_docx_font(document: Document) -> None:
    """Set conservative Chinese-friendly defaults."""
    styles = document.styles
    for style_name in ["Normal", "Body Text"]:
        if style_name in styles:
            style = styles[style_name]
            style.font.name = "宋体"
            style._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
            style.font.size = Pt(10.5)
    for style_name in ["Title", "Heading 1", "Heading 2", "Heading 3"]:
        if style_name in styles:
            style = styles[style_name]
            style.font.name = "宋体"
            style._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")


def set_margins(document: Document) -> None:
    for section in document.sections:
        section.top_margin = Cm(2.54)
        section.bottom_margin = Cm(2.54)
        section.left_margin = Cm(2.54)
        section.right_margin = Cm(2.54)


def add_heading_safe(document: Document, text: str, level: int = 1):
    p = document.add_heading(text, level=level)
    for run in p.runs:
        run.font.name = "宋体"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    return p


def add_paragraph_safe(document: Document, text: str = "", bold: bool = False, italic: bool = False, align=None):
    p = document.add_paragraph()
    r = p.add_run(text)
    r.bold = bold
    r.italic = italic
    r.font.name = "宋体"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    r.font.size = Pt(10.5)
    if align is not None:
        p.alignment = align
    return p


def add_picture_with_caption(document: Document, fig_path: Path, caption: str, width_inches: float = 6.2) -> bool:
    if not fig_path.exists():
        add_paragraph_safe(document, f"[缺失图片：{fig_path.name}]", italic=True, align=WD_ALIGN_PARAGRAPH.CENTER)
        add_paragraph_safe(document, caption, align=WD_ALIGN_PARAGRAPH.CENTER)
        return False
    p = document.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    try:
        run.add_picture(str(fig_path), width=Inches(width_inches))
        cap = document.add_paragraph()
        cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = cap.add_run(caption)
        r.font.name = "宋体"
        r._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
        r.font.size = Pt(10)
        return True
    except Exception as exc:
        add_paragraph_safe(document, f"[图片插入失败：{fig_path.name}; {exc}]", italic=True, align=WD_ALIGN_PARAGRAPH.CENTER)
        add_paragraph_safe(document, caption, align=WD_ALIGN_PARAGRAPH.CENTER)
        return False


def count_docx_paragraphs(document: Document) -> int:
    return len(document.paragraphs)


def has_text(document: Document, needle: str) -> bool:
    needle_low = needle.lower()
    return any(needle_low in p.text.lower() for p in document.paragraphs)


