def find_project_root() -> Path:
    """Find project root from script path or current working directory."""
    candidates: List[Path] = []
    try:
        candidates.append(Path(__file__).resolve().parent)
    except Exception:
        pass
    candidates.append(Path.cwd().resolve())

    expanded: List[Path] = []
    for c in candidates:
        expanded.extend([c, *c.parents])

    seen = set()
    for p in expanded:
        if p in seen:
            continue
        seen.add(p)
        if (p / "outputs" / "tables").exists() and (p / "outputs" / "figures").exists():
            return p
        if (p / "src").exists() and (p / "outputs").exists():
            return p
    # fallback: current working directory
    return Path.cwd().resolve()


def ensure_dirs(root: Path) -> Tuple[Path, Path, Path]:
    table_dir = root / "outputs" / "tables"
    fig_dir = root / "outputs" / "figures"
    report_dir = root / "reports"
    table_dir.mkdir(parents=True, exist_ok=True)
    fig_dir.mkdir(parents=True, exist_ok=True)
    report_dir.mkdir(parents=True, exist_ok=True)
    return table_dir, fig_dir, report_dir


def norm_text(x: object) -> str:
    return "" if x is None else str(x).strip()


def safe_float(x: object, default: Optional[float] = None) -> Optional[float]:
    s = norm_text(x)
    if not s:
        return default
    s = s.replace("R2=", "").replace("R²=", "").replace("RMSE=", "").replace("MAE=", "")
    s = s.replace("Coverage=", "").replace("N=", "").replace(",", "")
    try:
        return float(s)
    except Exception:
        m = re.search(r"-?\d+(?:\.\d+)?", s)
        if m:
            try:
                return float(m.group(0))
            except Exception:
                return default
    return default


