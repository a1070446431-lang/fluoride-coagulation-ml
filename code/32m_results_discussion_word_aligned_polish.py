def read_csv_safely(path: Path) -> pd.DataFrame:
    if not path.exists():
        return pd.DataFrame()
    encodings = ["utf-8-sig", "utf-8", "gbk", "gb18030"]
    for enc in encodings:
        try:
            return pd.read_csv(path, encoding=enc)
        except Exception:
            continue
    try:
        return pd.read_csv(path)
    except Exception:
        return pd.DataFrame()


def read_text_safely(path: Path) -> str:
    if not path.exists():
        return ""
    for enc in ["utf-8-sig", "utf-8", "gbk", "gb18030"]:
        try:
            return path.read_text(encoding=enc)
        except Exception:
            continue
    try:
        return path.read_text(errors="ignore")
    except Exception:
        return ""


def normalize_colname(name: str) -> str:
    return str(name).strip().lower().replace(" ", "_").replace("-", "_")


def find_value_by_keywords(df: pd.DataFrame, keywords: List[str]) -> Optional[str]:
    """
    Search a DataFrame for a value whose column name or nearby cell contains all keywords.
    This is intentionally flexible because previous table schemas changed across steps.
    """
    if df.empty:
        return None

    norm_cols = {col: normalize_colname(col) for col in df.columns}

    # 1) direct column match
    for col, norm_col in norm_cols.items():
        if all(k.lower() in norm_col for k in keywords):
            s = df[col].dropna()
            if len(s) > 0:
                return str(s.iloc[0])

    # 2) search cell text patterns key=value
    text = "\n".join(df.astype(str).fillna("").values.flatten().tolist())
    for k in keywords:
        pattern = re.compile(rf"{re.escape(k)}\s*[:=]\s*([^\n,;]+)", re.IGNORECASE)
        m = pattern.search(text)
        if m:
            return m.group(1).strip()

    return None


def parse_float(value: Optional[str], default: float) -> float:
    if value is None:
        return default
    try:
        m = re.search(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?", str(value))
        if m:
            return float(m.group(0))
    except Exception:
        pass
    return default


def parse_int(value: Optional[str], default: int) -> int:
    if value is None:
        return default
    try:
        m = re.search(r"[-+]?\d+", str(value))
        if m:
            return int(m.group(0))
    except Exception:
        pass
    return default


def first_existing(paths: List[Path]) -> Optional[Path]:
    for p in paths:
        if p.exists():
            return p
    return None


