def find_project_root() -> Path:
    """
    Find the project root robustly when this script is run from project root or src/.
    Expected project structure:
        project_root/
            outputs/tables/
            outputs/figures/
            reports/
            src/
            data/
    """
    here = Path(__file__).resolve().parent
    candidates = [
        here,
        here.parent,
        Path.cwd().resolve(),
        Path.cwd().resolve().parent,
    ]

    for c in candidates:
        if (c / "outputs").exists() and ((c / "src").exists() or (c / "data").exists() or (c / "reports").exists()):
            return c

    # Fallback: if script is inside src, use parent
    if here.name.lower() == "src":
        return here.parent

    return here


