"""
34b_free_fluoride_fraction_random_split_sensitivity.py

Purpose
-------
Evaluate whether correcting the mixed 0–1 / 0–100 scale in "游离氟占比"
materially changes the established RANDOM-SPLIT result.

This script deliberately tests only the random-split branch first.
It does NOT modify:
    - model_ready_v1.csv
    - model_ready_v1_with_source.csv
    - any manuscript figure
    - any grouped-validation / AD result

Method
------
1. Dynamically import the existing 24_exact_ablation_selected_fusion.py workflow.
2. Run the EXACT SAME workflow on:
       A) official model_ready_v1.csv
       B) candidate corrected dataset generated by script 34a
3. Use the same seeds, split ratios, feature engineering, feature ranking,
   K search, models, validation-weight search, and pooled metrics.
4. Compare the established "Selected_Weighted_4Model" result first.
5. Save all outputs with the 34b prefix so no historical results are overwritten.

Place in:
    fluoride_coagulation_ml_project/src/

Run directly in PyCharm.
"""

from __future__ import annotations

import importlib.util
import platform
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd


SCRIPT_NAME = "34b_free_fluoride_fraction_random_split_sensitivity"

FOCUS_METHODS = [
    "Selected_Weighted_4Model",
    "Selected_CatBoost_HGB_Weighted",
    "Selected_CatBoost",
    "Selected_HistGradientBoosting",
]

EXPECTED_RECORDS = 1011
EXPECTED_OFFICIAL_POOLED_R2 = 0.882
R2_STABILITY_TOL = 0.02
RMSE_STABILITY_TOL = 1.00
MAE_STABILITY_TOL = 1.00


def log(msg: str) -> None:
    print(msg, flush=True)


def locate_root() -> Path:
    here = Path(__file__).resolve()
    for p in [here.parent, *here.parents]:
        if (p / "data").exists() and (p / "outputs").exists():
            return p
    return here.parent.parent


def find_file_upwards(start_path: Path, filename: str) -> Path:
    start_path = start_path.resolve()
    for root in [start_path.parent, *start_path.parents]:
        for candidate in (root / filename, root / "src" / filename):
            if candidate.exists():
                return candidate
    raise FileNotFoundError(f"Cannot find required script: {filename}")


def import_script24():
    path = find_file_upwards(Path(__file__), "24_exact_ablation_selected_fusion.py")

    log("=" * 92)
    log("Importing established exact-ablation workflow:")
    log(str(path))
    log("=" * 92)

    spec = importlib.util.spec_from_file_location(
        "exact_ablation_24_for_sensitivity",
        path,
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def verify_candidate_pair(official_path: Path, candidate_path: Path) -> None:
    if not official_path.exists():
        raise FileNotFoundError(f"Official dataset not found: {official_path}")
    if not candidate_path.exists():
        raise FileNotFoundError(
            f"Candidate corrected dataset not found: {candidate_path}\n"
            "Run 34a_audit_and_fix_free_fluoride_fraction_scale.py first."
        )

    a = pd.read_csv(official_path)
    b = pd.read_csv(candidate_path)

    if len(a) != EXPECTED_RECORDS or len(b) != EXPECTED_RECORDS:
        raise RuntimeError(
            f"Expected {EXPECTED_RECORDS} records; observed official={len(a)}, candidate={len(b)}."
        )

    if list(a.columns) != list(b.columns):
        raise RuntimeError("Official and candidate datasets have different columns.")

    if "游离氟占比" not in a.columns:
        raise RuntimeError("Column 游离氟占比 not found.")

    # All fields except 游离氟占比 must be scientifically identical.
    #
    # IMPORTANT:
    # The candidate CSV was written once by pandas in script 34a. A small number
    # of floating-point cells can therefore differ at the last machine/decimal
    # digit after CSV serialization, even though their scientific values are
    # unchanged. DataFrame.equals() is too strict for this audit.
    #
    # We therefore compare:
    #   - numeric columns with np.isclose(rtol=1e-12, atol=1e-12, equal_nan=True)
    #   - non-numeric columns exactly after normalizing missing values
    compare_cols = [c for c in a.columns if c != "游离氟占比"]

    scientific_differences = []

    for col in compare_cols:
        a_num = pd.to_numeric(a[col], errors="coerce")
        b_num = pd.to_numeric(b[col], errors="coerce")

        # Treat as numeric only when every non-missing original entry is numeric.
        a_nonmissing = a[col].notna()
        b_nonmissing = b[col].notna()
        numeric_like = (
            int(a_num.notna().sum()) == int(a_nonmissing.sum())
            and int(b_num.notna().sum()) == int(b_nonmissing.sum())
        )

        if numeric_like:
            same = np.isclose(
                a_num.to_numpy(dtype=float),
                b_num.to_numpy(dtype=float),
                rtol=1e-12,
                atol=1e-12,
                equal_nan=True,
            )
        else:
            a_txt = a[col].fillna("<NA>").astype(str).str.strip()
            b_txt = b[col].fillna("<NA>").astype(str).str.strip()
            same = (a_txt == b_txt).to_numpy()

        bad_idx = np.where(~same)[0]
        for idx in bad_idx:
            scientific_differences.append(
                {
                    "row_index": int(idx),
                    "column": col,
                    "official": a.iloc[idx][col],
                    "candidate": b.iloc[idx][col],
                }
            )

    if scientific_differences:
        diff_df = pd.DataFrame(scientific_differences)
        print("\n[STOP] Scientifically meaningful differences were found outside 游离氟占比:")
        print(diff_df.head(20).to_string(index=False))
        raise RuntimeError(
            "Candidate dataset has meaningful differences outside 游离氟占比. "
            f"Cells affected: {len(scientific_differences)}. Stop."
        )

    log("  all other fields    = scientifically identical (numeric tolerance 1e-12)")

    a_ff = pd.to_numeric(a["游离氟占比"], errors="coerce")
    b_ff = pd.to_numeric(b["游离氟占比"], errors="coerce")
    changed = ~(
        (a_ff.isna() & b_ff.isna())
        | np.isclose(a_ff.fillna(0), b_ff.fillna(0), atol=1e-12)
    )

    changed_n = int(changed.sum())
    if changed_n != 234:
        log(
            f"[WARNING] Expected 234 corrected rows from 34a, "
            f"but observed {changed_n} changed rows."
        )

    if int((b_ff.dropna() > 1).sum()) != 0:
        raise RuntimeError("Candidate correction failed: corrected 游离氟占比 still contains values > 1.")

    log("\nCandidate verification passed:")
    log(f"  records             = {len(b)}")
    log(f"  changed rows        = {changed_n}")
    log(f"  corrected min/max   = {b_ff.min():.6g} / {b_ff.max():.6g}")
    log(f"  all other fields    = identical")


def run_exact_workflow(m24, data_path: Path, label: str):
    """
    Patch only the DATA_FILE pointer used by script 19/18.
    Everything else is inherited unchanged from the established workflow.
    """
    log("\n" + "#" * 92)
    log(f"RUNNING DATASET: {label}")
    log(f"DATA_FILE = {data_path}")
    log("#" * 92)

    m24.sf19.fe18.DATA_FILE = data_path

    y, X_raw, X_eng, X_mix = m24.sf19.prepare_feature_sets()

    log("\nFeature-set confirmation:")
    log(f"  N                  = {len(y)}")
    log(f"  Raw compact        = {X_raw.shape}")
    log(f"  Engineered compact = {X_eng.shape}")
    log(f"  Raw + Engineered   = {X_mix.shape}")
    log(f"  Seeds              = {m24.sf19.SEEDS}")
    log(f"  K options          = {m24.sf19.K_OPTIONS}")

    result = m24.evaluate_exact_ablation(
        X_raw=X_raw,
        X_mix=X_mix,
        y=y,
    )

    test_df, candidate_df, weight_df, prediction_df, feature_rank_df = result
    summary_df = m24.summarize_exact_ablation(test_df, prediction_df)

    for df in (test_df, candidate_df, weight_df, prediction_df, feature_rank_df, summary_df):
        df.insert(0, "Dataset_Version", label)

    return {
        "test": test_df,
        "candidate": candidate_df,
        "weights": weight_df,
        "predictions": prediction_df,
        "feature_ranking": feature_rank_df,
        "summary": summary_df,
    }


def build_comparison(original_summary: pd.DataFrame, corrected_summary: pd.DataFrame) -> pd.DataFrame:
    cols = [
        "Method",
        "R2_mean",
        "R2_std",
        "RMSE_mean",
        "RMSE_std",
        "MAE_mean",
        "MAE_std",
        "Pooled_R2",
        "Pooled_RMSE",
        "Pooled_MAE",
        "n_pooled",
    ]

    a = original_summary[cols].copy()
    b = corrected_summary[cols].copy()

    a = a.rename(columns={c: f"Original_{c}" for c in cols if c != "Method"})
    b = b.rename(columns={c: f"Corrected_{c}" for c in cols if c != "Method"})

    comp = a.merge(b, on="Method", how="outer")

    comp["Delta_Pooled_R2"] = comp["Corrected_Pooled_R2"] - comp["Original_Pooled_R2"]
    comp["Delta_Pooled_RMSE"] = comp["Corrected_Pooled_RMSE"] - comp["Original_Pooled_RMSE"]
    comp["Delta_Pooled_MAE"] = comp["Corrected_Pooled_MAE"] - comp["Original_Pooled_MAE"]

    comp["Abs_Delta_Pooled_R2"] = comp["Delta_Pooled_R2"].abs()
    comp["Abs_Delta_Pooled_RMSE"] = comp["Delta_Pooled_RMSE"].abs()
    comp["Abs_Delta_Pooled_MAE"] = comp["Delta_Pooled_MAE"].abs()

    comp["Sensitivity_Judgement"] = np.where(
        (comp["Abs_Delta_Pooled_R2"] <= R2_STABILITY_TOL)
        & (comp["Abs_Delta_Pooled_RMSE"] <= RMSE_STABILITY_TOL)
        & (comp["Abs_Delta_Pooled_MAE"] <= MAE_STABILITY_TOL),
        "Stable under scale correction",
        "Materially affected; further review required",
    )

    comp["_focus_order"] = comp["Method"].apply(
        lambda x: FOCUS_METHODS.index(x) if x in FOCUS_METHODS else 999
    )
    comp = comp.sort_values(
        ["_focus_order", "Corrected_Pooled_R2"],
        ascending=[True, False],
    ).drop(columns="_focus_order")

    return comp


def main() -> None:
    t0 = time.time()
    root = locate_root()

    official_path = root / "data" / "processed" / "model_ready_v1.csv"
    corrected_path = (
        root
        / "data"
        / "processed"
        / "model_ready_v1_free_fraction_fixed_candidate.csv"
    )

    out_tables = root / "outputs" / "jece_final_package" / "tables"
    out_reports = root / "outputs" / "jece_final_package" / "reports"
    out_logs = root / "outputs" / "jece_final_package" / "logs"

    for d in (out_tables, out_reports, out_logs):
        d.mkdir(parents=True, exist_ok=True)

    # ---------------------------------------------------------
    # 1. Verify that 34a changed only 游离氟占比
    # ---------------------------------------------------------
    verify_candidate_pair(official_path, corrected_path)

    # ---------------------------------------------------------
    # 2. Import the established 24 -> 19 -> 18 workflow
    # ---------------------------------------------------------
    m24 = import_script24()

    # ---------------------------------------------------------
    # 3. Re-run exact RANDOM-SPLIT workflow twice
    # ---------------------------------------------------------
    original = run_exact_workflow(
        m24,
        official_path,
        "Original_archived_scale",
    )

    corrected = run_exact_workflow(
        m24,
        corrected_path,
        "Corrected_free_fraction_scale",
    )

    # ---------------------------------------------------------
    # 4. Compare
    # ---------------------------------------------------------
    comparison = build_comparison(
        original["summary"],
        corrected["summary"],
    )

    # Save complete sensitivity evidence.
    pd.concat(
        [original["summary"], corrected["summary"]],
        ignore_index=True,
    ).to_csv(
        out_tables / "34b_random_split_scale_sensitivity_all_method_summary.csv",
        index=False,
        encoding="utf-8-sig",
    )

    comparison.to_csv(
        out_tables / "34b_random_split_scale_sensitivity_comparison.csv",
        index=False,
        encoding="utf-8-sig",
    )

    pd.concat(
        [original["test"], corrected["test"]],
        ignore_index=True,
    ).to_csv(
        out_tables / "34b_random_split_scale_sensitivity_seed_results.csv",
        index=False,
        encoding="utf-8-sig",
    )

    pd.concat(
        [original["weights"], corrected["weights"]],
        ignore_index=True,
    ).to_csv(
        out_tables / "34b_random_split_scale_sensitivity_weights.csv",
        index=False,
        encoding="utf-8-sig",
    )

    # ---------------------------------------------------------
    # 5. Console decision for the manuscript's current best model
    # ---------------------------------------------------------
    focus = comparison[
        comparison["Method"] == "Selected_Weighted_4Model"
    ].copy()

    if focus.empty:
        raise RuntimeError(
            "Selected_Weighted_4Model was not found. "
            "Do not interpret the sensitivity result."
        )

    row = focus.iloc[0]

    manuscript_reference_diff = (
        float(row["Original_Pooled_R2"]) - EXPECTED_OFFICIAL_POOLED_R2
    )

    stable = (
        abs(float(row["Delta_Pooled_R2"])) <= R2_STABILITY_TOL
        and abs(float(row["Delta_Pooled_RMSE"])) <= RMSE_STABILITY_TOL
        and abs(float(row["Delta_Pooled_MAE"])) <= MAE_STABILITY_TOL
    )

    lines = [
        "=" * 92,
        "34b FREE-FLUORIDE SCALE SENSITIVITY — RANDOM SPLIT ONLY",
        "=" * 92,
        "",
        "Focus method: Selected_Weighted_4Model",
        "",
        f"Original pooled R2   = {row['Original_Pooled_R2']:.6f}",
        f"Corrected pooled R2  = {row['Corrected_Pooled_R2']:.6f}",
        f"Delta pooled R2      = {row['Delta_Pooled_R2']:+.6f}",
        "",
        f"Original pooled RMSE = {row['Original_Pooled_RMSE']:.6f}",
        f"Corrected pooled RMSE= {row['Corrected_Pooled_RMSE']:.6f}",
        f"Delta pooled RMSE    = {row['Delta_Pooled_RMSE']:+.6f}",
        "",
        f"Original pooled MAE  = {row['Original_Pooled_MAE']:.6f}",
        f"Corrected pooled MAE = {row['Corrected_Pooled_MAE']:.6f}",
        f"Delta pooled MAE     = {row['Delta_Pooled_MAE']:+.6f}",
        "",
        f"Original pooled R2 - manuscript 0.882 = {manuscript_reference_diff:+.6f}",
        "",
        "Sensitivity threshold used here:",
        f"  |Delta R2|   <= {R2_STABILITY_TOL}",
        f"  |Delta RMSE| <= {RMSE_STABILITY_TOL}",
        f"  |Delta MAE|  <= {MAE_STABILITY_TOL}",
        "",
        (
            "DECISION: RANDOM-SPLIT CONCLUSION IS STABLE UNDER SCALE CORRECTION."
            if stable
            else
            "DECISION: RANDOM-SPLIT RESULT IS MATERIALLY AFFECTED; STOP BEFORE MODIFYING THE MANUSCRIPT."
        ),
        "",
        "No grouped-validation or applicability-domain result was changed in this step.",
    ]

    runtime = time.time() - t0
    lines += [
        "",
        f"runtime_s={runtime:.2f}",
        f"python={sys.version.split()[0]}",
        f"platform={platform.platform()}",
        "=" * 92,
    ]

    report = "\n".join(lines) + "\n"

    report_path = out_reports / f"{SCRIPT_NAME}_decision.txt"
    log_path = out_logs / f"{SCRIPT_NAME}.log"

    report_path.write_text(report, encoding="utf-8")
    log_path.write_text(report, encoding="utf-8")

    print("\n" + report)

    print("\nFocused comparison:")
    display_cols = [
        "Method",
        "Original_Pooled_R2",
        "Corrected_Pooled_R2",
        "Delta_Pooled_R2",
        "Original_Pooled_RMSE",
        "Corrected_Pooled_RMSE",
        "Delta_Pooled_RMSE",
        "Original_Pooled_MAE",
        "Corrected_Pooled_MAE",
        "Delta_Pooled_MAE",
        "Sensitivity_Judgement",
    ]
    print(
        comparison[
            comparison["Method"].isin(FOCUS_METHODS)
        ][display_cols].to_string(index=False)
    )

    print(f"\nCompleted in {runtime:.2f} s")


if __name__ == "__main__":
    main()
